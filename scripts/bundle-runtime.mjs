/**
 * v5 内置 runtime bundle:esbuild 把 hmharness 的 desktop-host 连同全部 import 链
 * 打成开箱即用的自包含产物(hmharness 仓库零改动,构建期从相邻仓库读源码)。
 *
 * 产物布局(dev 与安装包 extraResources 同构;resources/ 整目录平铺到
 * <install>/resources/):
 *   resources/runtime/runtime.cjs     进程入口。desktop-host 链含顶层 await(ESM
 *                                     only),故真身是 ESM bundle,内嵌进 CJS 外壳
 *                                     经 data: URL 动态 import 启动;bundle 内部
 *                                     仅剩 node: 内置依赖(hmharness 无其他 npm
 *                                     运行时依赖,web 的 qrcode 已一并打平)。
 *   resources/runtime/task-runner.js  server.ts 执行任务时 spawn 的子进程伴随件
 *                                     (独立进程边界,不可内联;无 TLA,打成 CJS)。
 *   resources/package.json            构建期生成的版本元数据:server.ts 经
 *                                     createRequire(import.meta.url)('../package.json')
 *                                     读 DAEMON_VERSION → 引导行 version=hmharness
 *                                     版本;无 type 字段,同时钉住 runtime/ 子树的
 *                                     .js 一律按 CJS 解析(apps/desktop 根的
 *                                     package.json 是 type:module)。
 *
 * import.meta.url/dirname 经 esbuild define 重定向到 globalThis 桥变量 —— data:
 * 模块自身的 import.meta 是 data: URL,而 server.ts 靠它解析同目录 task-runner
 * 与版本文件;外壳在 import 前把真实位置放进 globalThis。
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const harnessRoot = process.env.HMHARNESS_ROOT ?? join(root, '..', 'hmharness');
const outDir = join(root, 'apps', 'desktop', 'resources', 'runtime');
const harnessVersion = JSON.parse(readFileSync(join(harnessRoot, 'package.json'), 'utf8')).version;

mkdirSync(outDir, { recursive: true });

// data: URL 模块没有可用的 import.meta 值 → define 换成桥变量,由 CJS 外壳注入
const RUNTIME_BANNER = `
const __hmhMeta = globalThis.__HMH_BUNDLED_META__;
const __hmhBundledMetaUrl = __hmhMeta.url;
const __hmhBundledMetaDirname = __hmhMeta.dirname;
const __hmhBundledMetaFilename = __hmhMeta.filename;
`.trim();

// 1) desktop-host → ESM bundle(顶层 await 只能活在 ESM)
const esm = await build({
  entryPoints: [join(harnessRoot, 'packages', 'web', 'src', 'desktop-host.ts')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  external: ['node:*'],
  define: {
    'import.meta.url': '__hmhBundledMetaUrl',
    'import.meta.dirname': '__hmhBundledMetaDirname',
    'import.meta.filename': '__hmhBundledMetaFilename',
  },
  banner: { js: RUNTIME_BANNER },
  write: false,
  metafile: true,
  logLevel: 'silent',
});

// 2) task-runner → CJS 伴随件(子进程直跑,无 TLA 无 import.meta)
await build({
  entryPoints: [join(harnessRoot, 'packages', 'web', 'src', 'task-runner.ts')],
  outfile: join(outDir, 'task-runner.js'),
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  external: ['node:*'],
  logLevel: 'silent',
});

// 3) CJS 外壳:内嵌 ESM bundle(JSON.stringify 转义,无体积膨胀),data: URL 启动
const esmText = esm.outputFiles[0].text;
const runtimeCjs = `//! HMH Desktop 内置 runtime(v5)— 由 scripts/bundle-runtime.mjs 生成,勿手改。
//! 真身是内嵌的 hmharness desktop-host ESM bundle(顶层 await 需 ESM,node: 内置
//! 全 external),经 data: URL 动态 import 启动;import.meta.* 已被重定向到
//! globalThis.__HMH_BUNDLED_META__(本文件的真实位置)。
const { pathToFileURL } = require('node:url');
globalThis.__HMH_BUNDLED_META__ = {
  url: pathToFileURL(__filename).href,
  dirname: __dirname,
  filename: __filename,
};
const RUNTIME_MJS = ${JSON.stringify(esmText)};
import('data:text/javascript;charset=utf-8,' + encodeURIComponent(RUNTIME_MJS)).catch((err) => {
  process.stderr.write('[hmh-desktop runtime] bundled host failed to boot: ' + ((err && err.stack) || err) + '\\n');
  process.exit(1);
});
`;
writeFileSync(join(outDir, 'runtime.cjs'), runtimeCjs);

// 4) 版本元数据(server.ts 的 '../package.json' 版本源;同时钉住子树 CJS 解析)
writeFileSync(join(root, 'apps', 'desktop', 'resources', 'package.json'), `${JSON.stringify({
  name: '@hmharness/web',
  version: harnessVersion,
  description: 'Bundled hmharness runtime metadata (generated by scripts/bundle-runtime.mjs; version source for the desktop host)',
}, null, 2)}\n`);

// 摘要:体积 + 打进的 npm 包(应只有 hmharness 自身 workspace + qrcode 链)
const kb = Math.round(Buffer.byteLength(runtimeCjs) / 1024);
const npmPkgs = [...new Set(Object.keys(esm.metafile.inputs)
  .map((i) => i.match(/node_modules[/\\]((@[^/\\]+[/\\])?[^\\/_@][^\\/]*)/)?.[1])
  .filter(Boolean))];
console.log(`runtime.cjs ${kb}KB + task-runner.js (hmharness ${harnessVersion}, ${Object.keys(esm.metafile.inputs).length} 个模块)`);
console.log(`npm 依赖打进: ${npmPkgs.join(', ') || '(无)'}`);
