export type Strings = typeof zh;

const dicts: Record<Locale, Strings> = { zh, en };

/** localStorage 显式选择 > 系统语言。 */
export function getLocale(): Locale {
  try {
    const v = window.localStorage.getItem('hmh.locale');
    if (v === 'zh' || v === 'en') return v;
  } catch { /* 私有模式 */ }
  const nav = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : 'zh';
  return nav.startsWith('zh') ? 'zh' : 'en';
}

export function saveLocale(l: Locale): void {
  try { window.localStorage.setItem('hmh.locale', l); } catch { /* 私有模式 */ }
  if (typeof document !== 'undefined') document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en';
}

export function stringsFor(l: Locale): Strings {
  return dicts[l];
}

/** 语言 hook:切语言触发重渲染,<html lang> 同步。 */
export function useLocale(): { locale: Locale; L: Strings; setLocale: (l: Locale) => void } {
  const [locale, set] = useState<Locale>(getLocale);
  useEffect(() => {
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en';
  }, [locale]);
  return {
    locale,
    L: stringsFor(locale),
    setLocale: (l: Locale): void => {
      saveLocale(l);
      set(l);
    },
  };
}
